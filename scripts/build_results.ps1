<#
    Build RESULTS.md: every task, the query you wrote, and the table it returns.

    Examples:
      .\scripts\build_results.ps1
      .\scripts\build_results.ps1 -Folder solutions
#>
param(
    [string]$Folder = "answers",
    [string]$Db = $env:DATABASE_URL,
    [string]$Psql = ""
)

if ([string]::IsNullOrWhiteSpace($Db)) {
    $Db = "postgres://nusantara:nusantara@localhost:5433/nusantara"
}
if ([string]::IsNullOrWhiteSpace($Psql)) {
    $found = Get-Command psql -ErrorAction SilentlyContinue
    if ($found) {
        $Psql = $found.Source
    } else {
        $candidate = Get-ChildItem "C:\Program Files\PostgreSQL\*\bin\psql.exe" -ErrorAction SilentlyContinue |
                     Sort-Object FullName -Descending | Select-Object -First 1
        if (-not $candidate) {
            Write-Host "psql not found. Install PostgreSQL or pass -Psql with the full path." -ForegroundColor Red
            exit 1
        }
        $Psql = $candidate.FullName
    }
}

$lines = @(
    "# Results",
    "",
    "Generated by ``scripts/build_results.ps1`` from ``$Folder/``, run against the Nusantara Living database.",
    ""
)

foreach ($expected in Get-ChildItem "expected\*.csv" | Sort-Object Name) {
    $num = $expected.BaseName
    $file = Get-ChildItem "$Folder\$($num)_*.sql" -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $file) { continue }

    $all = Get-Content $file.FullName
    $query = $all | Where-Object { -not $_.Trim().StartsWith("--") } | Where-Object { $_.Trim() -ne "" }
    if (-not $query) { continue }

    $heading = ($all[0] -replace '^-- ', '')
    $ask = ($all[1] -replace '^-- ', '')
    $table = & $Psql $Db -q -P pager=off -f $file.FullName 2>&1 | Select-Object -First 40

    $lines += "## $heading"
    $lines += ""
    $lines += $ask
    $lines += ""
    $lines += '```sql'
    $lines += $query
    $lines += '```'
    $lines += ""
    $lines += '```'
    $lines += $table
    $lines += '```'
    $lines += ""
}

$lines | Set-Content -Encoding UTF8 "RESULTS.md"
Write-Host "wrote RESULTS.md"
