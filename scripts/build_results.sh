#!/usr/bin/env bash
# Build RESULTS.md: every task, the query you wrote, and the table it returns.
# Usage: bash scripts/build_results.sh [answers|solutions]
set -u

DIR="${1:-answers}"
DB="${DATABASE_URL:-postgres://nusantara:nusantara@localhost:5433/nusantara}"
OUT="RESULTS.md"

{
    echo "# Results"
    echo
    echo "Generated by \`scripts/build_results.sh\` from \`$DIR/\`, run against the Nusantara Living database."
    echo
} > "$OUT"

for exp in expected/*.csv; do
    num="$(basename "$exp" .csv)"
    file="$(ls "$DIR"/${num}_*.sql 2>/dev/null | head -1)"
    [ -z "$file" ] && continue
    grep -qvE '^[[:space:]]*(--.*)?$' "$file" || continue

    title="$(sed -n '2p' "$file" | sed 's/^-- //')"
    heading="$(sed -n '1p' "$file" | sed 's/^-- //')"
    query="$(grep -vE '^[[:space:]]*--' "$file" | sed '/^[[:space:]]*$/d')"

    {
        echo "## $heading"
        echo
        echo "$title"
        echo
        echo '```sql'
        echo "$query"
        echo '```'
        echo
        echo '```'
        psql "$DB" -q -P pager=off -f "$file" 2>&1 | head -40
        echo '```'
        echo
    } >> "$OUT"
done

echo "wrote $OUT"
